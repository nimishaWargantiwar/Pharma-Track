package com.pharmatrack.ai.repository;

import com.pharmatrack.ai.entity.BatchAnalysisReport;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.EntityGraph;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Optional;

/**
 * Spring Data JPA repository for persistent AI Batch Analysis Reports.
 */
@Repository
public interface BatchAnalysisReportRepository extends JpaRepository<BatchAnalysisReport, Long> {

    @Override
    @EntityGraph(attributePaths = {"batch", "generatedByUser", "archivedByUser"})
    Optional<BatchAnalysisReport> findById(Long id);

    /**
     * Finds all reports for a specific batch in reverse chronological order.
     *
     * @param batchId physical batch ID
     * @return list of reports ordered newest first
     */
    @EntityGraph(attributePaths = {"batch", "generatedByUser", "archivedByUser"})
    List<BatchAnalysisReport> findByBatchIdOrderByCreatedAtDesc(Long batchId);

    /**
     * Finds active or archived reports for a specific batch in reverse chronological order.
     *
     * @param batchId  physical batch ID
     * @param archived whether to filter for archived (true) or active (false)
     * @return list of matching reports ordered newest first
     */
    @EntityGraph(attributePaths = {"batch", "generatedByUser", "archivedByUser"})
    List<BatchAnalysisReport> findByBatchIdAndArchivedOrderByCreatedAtDesc(Long batchId, boolean archived);

    /**
     * Finds paginated reports for a specific batch in reverse chronological order.
     *
     * @param batchId pageable pagination parameters
     * @return page of reports ordered newest first
     */
    @EntityGraph(attributePaths = {"batch", "generatedByUser", "archivedByUser"})
    Page<BatchAnalysisReport> findByBatchIdOrderByCreatedAtDesc(Long batchId, Pageable pageable);

    /**
     * Finds paginated active or archived reports for a specific batch in reverse chronological order.
     *
     * @param batchId  physical batch ID
     * @param archived whether to filter for archived (true) or active (false)
     * @param pageable pagination parameters
     * @return page of reports ordered newest first
     */
    @EntityGraph(attributePaths = {"batch", "generatedByUser", "archivedByUser"})
    Page<BatchAnalysisReport> findByBatchIdAndArchivedOrderByCreatedAtDesc(Long batchId, boolean archived, Pageable pageable);

    /**
     * Finds all reports for a specific batch number in reverse chronological order.
     *
     * @param batchNumber business batch number
     * @return list of reports ordered newest first
     */
    List<BatchAnalysisReport> findByBatchBatchNumberOrderByCreatedAtDesc(String batchNumber);

    /**
     * Finds the most recent report for a batch with the specified lifecycle status.
     *
     * @param batchId physical batch ID
     * @param status  target report lifecycle status
     * @return matching report or empty Optional
     */
    Optional<BatchAnalysisReport> findFirstByBatchIdAndStatusOrderByCreatedAtDesc(Long batchId, com.pharmatrack.ai.entity.BatchAnalysisReportStatus status);

    /**
     * Finds a single report by client idempotency request ID.
     *
     * @param clientRequestId unique idempotency request ID
     * @return matching report or empty Optional
     */
    @EntityGraph(attributePaths = {"batch", "generatedByUser", "archivedByUser"})
    Optional<BatchAnalysisReport> findByClientRequestId(String clientRequestId);

    /**
     * Checks if a report exists with the given client idempotency request ID.
     *
     * @param clientRequestId unique idempotency request ID
     * @return true if exists
     */
    boolean existsByClientRequestId(String clientRequestId);

    /**
     * Finds a report detail scoped to its parent batch by physical IDs.
     *
     * @param id report ID
     * @param batchId physical batch ID
     * @return matching report or empty Optional
     */
    @EntityGraph(attributePaths = {"batch", "generatedByUser", "archivedByUser"})
    Optional<BatchAnalysisReport> findByIdAndBatchId(Long id, Long batchId);

    /**
     * Finds a report detail scoped to its parent batch by report ID and business batch number.
     *
     * @param id report ID
     * @param batchNumber business batch number
     * @return matching report or empty Optional
     */
    Optional<BatchAnalysisReport> findByIdAndBatchBatchNumber(Long id, String batchNumber);

    /**
     * Finds all reports generated by a specific user in reverse chronological order.
     *
     * @param userId user account ID
     * @return list of reports ordered newest first
     */
    List<BatchAnalysisReport> findByGeneratedByUserIdOrderByCreatedAtDesc(Long userId);
}
